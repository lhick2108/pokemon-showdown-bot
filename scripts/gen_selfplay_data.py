"""Bake the gen9 random-battle team data used by the Rust self-play pool (engine/src/selfplay.rs).

    python scripts/gen_selfplay_data.py [--cache .cache/randbats] [--out engine/data/randbats_gen9.txt]

Source: pkmn/randbats "full" joint-set data (the same file ``showdown_bot.sets`` samples opponent
sets from: exact ``level,item,ability,moves,tera`` keys with the number of times each set appeared in
100k generated teams) plus the dex (types, base stats, weight), max PP, the team-rule helpers
(weaknesses) and the per-set EV/IV spread that ``teams.ts`` would pick (``engine_state.randbats_evs_ivs``).
The output is a line-based text file (no JSON parser needed in Rust):

    S|species|level|type1|type2|hp|atk|def|spa|spd|spe|weightkg|base_species|weak,..|dweak,..|freezedry
    F|species|count|level|item|ability|move,move,..|tera|evs(6, ;)|ivs(6, ;)
    P|move|max_pp
"""
from __future__ import annotations

import argparse
from pathlib import Path

from showdown_bot import engine_state as es
from showdown_bot.sets import RandbatsData, to_id


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--cache", default=".cache/randbats")
    ap.add_argument("--out", default="engine/data/randbats_gen9.txt")
    args = ap.parse_args()
    data = RandbatsData.load("gen9randombattle", cache_dir=args.cache, max_age=0)
    sampler = es.TeamSampler(data)
    lines = ["# generated by scripts/gen_selfplay_data.py from pkmn/randbats full sets; do not edit"]
    moves: set[str] = set()
    skipped = []
    for sid in sampler.species_ids:
        info = sampler.info(sid)
        entry = es.dex_entry(sid)
        sets = data.full_sets(sid)
        if info is None or entry is None or not sets:
            skipped.append(sid)
            continue
        bs = entry["baseStats"]
        types = [t.lower() for t in entry["types"]]
        types = (types + ["typeless"])[:2]
        lines.append(
            "S|"
            + "|".join(
                [sid, str(info.level), types[0], types[1]]
                + [str(bs[k]) for k in es.STAT_KEYS]
                + [
                    repr(float(entry["weightkg"])),
                    info.base_species,
                    ",".join(sorted(t.lower() for t in info.weak)),
                    ",".join(sorted(t.lower() for t in info.double_weak)),
                    "1" if info.freeze_dry_weak else "0",
                ]
            )
        )
        for fs in sets:
            mv = [to_id(m) for m in fs.moves]
            moves.update(mv)
            item = to_id(fs.item) if fs.item else ""
            ab = to_id(fs.ability)
            evs, ivs = es.randbats_evs_ivs(sid, fs.level, mv, ab, item)
            lines.append(
                "F|"
                + "|".join(
                    [
                        sid,
                        str(int(fs.count)),
                        str(fs.level),
                        item,
                        ab,
                        ",".join(mv),
                        to_id(fs.tera_type),
                        ";".join(map(str, evs)),
                        ";".join(map(str, ivs)),
                    ]
                )
            )
    for m in sorted(moves):
        lines.append(f"P|{m}|{es._max_pp(m)}")
    Path(args.out).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(sampler.species_ids) - len(skipped)} species, {len(moves)} moves, skipped {skipped}")


if __name__ == "__main__":
    main()
